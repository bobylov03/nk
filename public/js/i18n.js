  function detect() {
    const q = new URLSearchParams(location.search).get('lang');
    if (q && DICT[q] !== undefined || q === 'ru') return q;
    try {
      const saved = localStorage.getItem('nc_lang');
      if (saved) return saved;
    } catch (e) { /* приватный режим */ }
    const nav = (navigator.language || 'ru').slice(0, 2).toLowerCase();
    return nav === 'ka' ? 'ka' : nav === 'ru' ? 'ru' : 'en';
  }

  const lang = detect();
  document.documentElement.lang = lang;

  window.NCI18N = {
    LANGS,
    lang,
    /* Перевод строки. Нет в словаре — возвращаем как есть. */
    t(str) {
      if (lang === 'ru') return str;
      const d = DICT[lang] || {};
      return d[str] !== undefined ? d[str] : str;
    },
    /* Поле контента с суффиксом языка: name → name_en → откат на name */
    pick(obj, field) {
      if (!obj) return '';
      if (lang === 'ru') return obj[field] || '';
      return obj[field + '_' + lang] || obj[field] || '';
    },
    set(id) {
      try { localStorage.setItem('nc_lang', id); } catch (e) { /* ничего */ }
      const u = new URL(location.href);
      u.searchParams.delete('lang');
      location.href = u.toString();
    },
    /* Переключатель в шапку */
    switcher() {
      return '<div class="lang" role="group" aria-label="Language">' +
        LANGS.map(l => `<button type="button" class="${l.id === lang ? 'on' : ''}" data-lang="${l.id}" title="${l.label}">${l.short}</button>`).join('') +
        '</div>';
    },
    /* Переводит статический текст: элементы с data-tr и всё внутри них */
    apply(root) {
      if (lang === 'ru') return;
      const scope = root || document;
      scope.querySelectorAll('[data-tr], [data-tr] *').forEach(el => {
        for (const node of el.childNodes) {
          if (node.nodeType === 3) {
            const t = node.nodeValue.trim();
            if (t) {
              const r = NCI18N.t(t);
              if (r !== t) node.nodeValue = node.nodeValue.replace(t, r);
            }
          }
        }
      });
    },
    bind(host) {
      (host || document).querySelectorAll('[data-lang]').forEach(b => {
        b.onclick = () => NCI18N.set(b.dataset.lang);
      });
    }
  };
